/**
 * build-land-asset.mjs
 * --------------------
 * One-shot build script: downloads Natural Earth "land 110m" (via the
 * world-atlas TopoJSON package) and converts it to Mercator-projected SVG
 * path strings fitted to the Near-East / Eastern-Mediterranean viewport used
 * by the historical maps on the /map page.
 *
 * Output: lib/geo/near-east-geo.ts  (committed; no runtime dependency)
 *
 * Run:  node scripts/build-land-asset.mjs
 */
import { feature } from 'topojson-client';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));

// ── Region viewport (degrees) ────────────────────────────────────────────────
const LON_MIN = 23.0;   // includes mainland Greece (Athens 23.7E)
const LON_MAX = 62.0;   // past the Persian Gulf
const LAT_MIN = 24.0;   // Nile delta + Persian Gulf visible
const LAT_MAX = 42.5;   // Black Sea rim / Anatolia north

const WIDTH = 1000;     // SVG viewBox width (units)

// ── Mercator math (unit sphere) ──────────────────────────────────────────────
const D2R = Math.PI / 180;
const mercY = (lat) => Math.log(Math.tan(Math.PI / 4 + (lat * D2R) / 2));

const LAMBDA0 = LON_MIN * D2R;
const Y_TOP = mercY(LAT_MAX);
const Y_BOT = mercY(LAT_MIN);
const SCALE = WIDTH / ((LON_MAX - LON_MIN) * D2R);
const HEIGHT = Math.round((Y_TOP - Y_BOT) * SCALE * 10) / 10;

function project(lon, lat) {
  const x = (lon * D2R - LAMBDA0) * SCALE;
  const y = (Y_TOP - mercY(Math.max(-85, Math.min(85, lat)))) * SCALE;
  return [x, y];
}

// ── Download land polygons ───────────────────────────────────────────────────
const URL = 'https://unpkg.com/world-atlas@2.0.2/land-110m.json';
console.log('fetching', URL);
const res = await fetch(URL);
if (!res.ok) throw new Error(`fetch failed: ${res.status}`);
const topology = await res.json();
const land = feature(topology, topology.objects.land);

// ── Build path string ────────────────────────────────────────────────────────
const r1 = (n) => Math.round(n * 10) / 10;
let d = '';
const polygons =
  land.type === 'FeatureCollection'
    ? land.features.flatMap((f) => (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates))
    : land.geometry.type === 'Polygon'
      ? [land.geometry.coordinates]
      : land.geometry.coordinates;

let pointCount = 0;
for (const poly of polygons) {
  for (const ring of poly) {
    ring.forEach(([lon, lat], i) => {
      const [x, y] = project(lon, lat);
      d += `${i === 0 ? 'M' : 'L'}${r1(x)},${r1(y)}`;
      pointCount++;
    });
    d += 'Z';
  }
}
console.log(`projected ${pointCount} points, path length ${d.length} chars`);

// ── Emit TS module ───────────────────────────────────────────────────────────
const out = `/**
 * AUTO-GENERATED by scripts/build-land-asset.mjs — do not edit by hand.
 * Natural Earth 110m land polygons, Mercator-projected to the historical-map
 * viewport (lon ${LON_MIN}..${LON_MAX}, lat ${LAT_MIN}..${LAT_MAX}).
 */

export const GEO = {
  W: ${WIDTH},
  H: ${HEIGHT},
  SCALE: ${SCALE},
  LAMBDA0: ${LAMBDA0},
  Y_TOP: ${Y_TOP},
} as const;

/** Project lon/lat (degrees) to SVG viewport coordinates. */
export function projectLonLat(lon: number, lat: number): [number, number] {
  const clamped = Math.max(-85, Math.min(85, lat));
  const x = (lon * (Math.PI / 180) - GEO.LAMBDA0) * GEO.SCALE;
  const y =
    (GEO.Y_TOP - Math.log(Math.tan(Math.PI / 4 + (clamped * (Math.PI / 180)) / 2))) * GEO.SCALE;
  return [x, y];
}

export const LAND_PATH = '${d}';
`;

const outPath = join(__dirname, '..', 'lib', 'geo', 'near-east-geo.ts');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out, 'utf8');
console.log('wrote', outPath);
